// Settings snapshot export (roadmap item 13, upstream #67): one click turns
// the loaded device configuration into a shareable JSON file. Sharing a
// device's configuration for troubleshooting previously meant walking the
// Serial API endpoint by endpoint; this lands in the tool the user already
// has open during support. Privacy mirrors the log export: the device
// identifier is the only value here that identifies the user's device, so it
// is redacted; every other value is a configuration number.
import { $ } from '../ui/dom.js';
import { log } from './log.js';
import { announceStatus } from '../ui/a11y.js';
import { downloadLogFile } from './log-export.js';

// [element id, JSON key] — every value is read from the live readout, so the
// export always matches what the user sees (and can act as a screenshot-
// equivalent for support). Labels that failed to load are collected instead
// of exported as garbage ('—'/'ERR'/'…').
const EXPORTED_VALUES = [
  ['version', 'firmwareVersion'],
  ['opmode', 'operatingMode'],
  ['commode', 'communicationMode'],
  ['speedVal', 'cursorSpeedLevel'],
  ['scrollVal', 'scrollLevel'],
  ['sipVal', 'sipThresholdhPa'],
  ['puffVal', 'puffThresholdhPa'],
  ['innerDeadzoneVal', 'innerDeadzone'],
  ['outerDeadzoneVal', 'outerDeadzone'],
  ['soundModeVal', 'soundFeedback'],
  ['lightModeVal', 'lightFeedback'],
  ['brightnessVal', 'ledBrightness'],
  ['debugModeVal', 'debugMode'],
  ['neutralVal', 'neutralPosition'],
  ['corner1', 'calibrationCorner1'],
  ['corner2', 'calibrationCorner2'],
  ['corner3', 'calibrationCorner3'],
  ['corner4', 'calibrationCorner4'],
];

const PLACEHOLDERS = new Set(['', '—', 'ERR', '…', '?']);

/**
 * Reads the loaded settings from the display into an export object. Values
 * that did not load are listed under `notLoaded` (with their JSON keys) so
 * support can tell "off" from "never loaded" — an export with holes is
 * still useful, but the holes must be visible.
 * @returns {{ device: string, exportedAt: string, settings: Object, notLoaded: string[], note: string }}
 */
export function collectSettingsExport() {
  const settings = {};
  const notLoaded = [];
  for (const [id, key] of EXPORTED_VALUES) {
    const v = (($(id)?.textContent ?? '') + '').trim();
    if (PLACEHOLDERS.has(v)) {
      notLoaded.push(key);
      continue;
    }
    settings[key] = v;
  }
  const model = (($('model')?.textContent ?? '') + '').trim();
  if (PLACEHOLDERS.has(model)) notLoaded.push('model');
  else settings.model = model;
  return {
    device: 'LipSync',
    exportedAt: new Date().toISOString(),
    settings,
    notLoaded,
    note:
      'Generated by LipSync Connect. The device identifier is redacted for privacy; ask the user for it separately if needed. ' +
      (notLoaded.length ? 'Values listed in notLoaded did not load from the device at export time.' : ''),
  };
}

/** Builds the downloadable file ({ text, filename }) for the current settings. */
export function buildSettingsExportFile() {
  const data = collectSettingsExport();
  const stamp = new Date().toISOString().slice(0, 19).replace(/[:T]/g, '-');
  return {
    text: JSON.stringify(data, null, 2) + '\n',
    filename: `lipsync-settings-${data.settings.firmwareVersion || 'device'}-${stamp}.json`,
  };
}

/**
 * The button action: download the JSON export and say so in the log (the
 * download lands in the same place the settings-backup download does, so
 * the user knows where to look).
 */
export function exportSettings() {
  const { text, filename } = buildSettingsExportFile();
  downloadLogFile({ text, filename });
  const missing = JSON.parse(text).notLoaded ?? [];
  const message = 'Settings exported' + (missing.length ? ` (${missing.length} value(s) had not loaded)` : '') + '.';
  log(message, 'log-info');
  announceStatus(message);
}
